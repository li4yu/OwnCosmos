export function formatChunkBlock(
  hits: {
    title: string;
    text: string;
    score: number;
    archiveType: string;
    sourceId: string;
    archiveItemId: string | null;
    chunkIndex: number;
  }[],
): string {
  if (hits.length === 0) return "（无命中）";
  return hits
    .map((h, i) => {
      const id = h.archiveItemId || h.sourceId;
      return [
        `[#${i + 1}] score=${h.score.toFixed(4)} type=${h.archiveType || "-"} id=${id} chunk=${h.chunkIndex}`,
        `标题：${h.title || "(无标题)"}`,
        `正文：${h.text}`,
      ].join("\n");
    })
    .join("\n\n");
}

export function buildRagUserMessage(
  corpus: "user" | "project",
  userMessage: string,
  chunks: string,
): string {
  if (corpus === "project") {
    return `用户问题：${userMessage}

（工具 semantic_search_project 结果）手册检索片段：
${chunks}`;
  }
  return `用户问题：${userMessage}

（工具 semantic_search_user 结果）馆藏检索片段（前缀含 created=创建或起始、archived=归档或最近一次；计次类另有 count/正文分日，勿混用）：
${chunks}`;
}
